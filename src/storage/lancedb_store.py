# Reverse index maintenance + count_documents_by_threads
# ----------------------------------------------------------------------


def _build_reverse_index_from_disk() -> None:
    """Populate the reverse index from a single LanceDB scan.

    Called lazily on the first ``count_documents_by_threads`` call, and
    on every ``reset_for_tests``. Subsequent mutations are maintained
    incrementally (``add_chunks`` / ``delete_by_doc_id`` /
    ``delete_by_thread_id`` each update the relevant slices).

    Tolerates failures: a corrupt / empty table just leaves the index
    empty and the next mutation rebuilds it.
    """
    with _reverse_index_lock:
        _doc_to_threads.clear()
        _thread_to_docs.clear()
        _thread_first_filename.clear()
        _thread_latest_ingested_at.clear()
    try:
        table = get_table()
        arrow_tbl = table.to_arrow()
        if arrow_tbl.num_rows == 0 or "thread_id" not in arrow_tbl.schema.names:
            return
        doc_ids = arrow_tbl.column("doc_id").to_pylist()
        tids = arrow_tbl.column("thread_id").to_pylist()
        filenames = arrow_tbl.column("filename").to_pylist()
        # v2.0.6 P2-1 — also read ``ingested_at`` so we can build the
        # per-thread max timestamp in one pass alongside the rest of
        # the index. Older tables (pre-2.0.6) may lack the column.
        ingested_ats: list[str] = []
        if "ingested_at" in arrow_tbl.schema.names:
            ingested_ats = arrow_tbl.column("ingested_at").to_pylist()
        with _reverse_index_lock:
            for idx, (doc_id, tid, fname) in enumerate(
                zip(doc_ids, tids, filenames)
            ):
                if not doc_id or doc_id == "__bootstrap__":
                    continue
                if not tid:
                    continue
                _doc_to_threads.setdefault(doc_id, set()).add(tid)
                _thread_to_docs.setdefault(tid, set()).add(doc_id)
                if tid not in _thread_first_filename:
                    _thread_first_filename[tid] = fname
                # Maintain max — ISO 8601 strings sort lexicographically
                # the same as chronologically when they share the ``Z``
                # suffix that ``ChunkRecord.ingested_at`` produces.
                if ingested_ats:
                    cur_ts = ingested_ats[idx]
                    if cur_ts:
                        prev = _thread_latest_ingested_at.get(tid, "")
                        if cur_ts > prev:
                            _thread_latest_ingested_at[tid] = cur_ts
    except Exception as exc:
        logger.warning(f"reverse index build failed: {exc}")


def count_documents_by_threads(
    tids: Iterable[str],
) -> dict[str, tuple[int, str]]:
    """For each requested thread_id, return ``(distinct_doc_count, first_filename)``.

    This is the N+1 fix for ``GET /sessions``. The previous code called
    ``list_documents(thread_id=tid)`` inside a loop over every session,
    each invocation doing a full LanceDB ``to_arrow()`` scan. For a
    user with 50 conversations this was 50 scans (~50×100 ms = ~5 s)
    every time the sidebar loaded. This function does ONE scan total
    (or zero scans if the reverse index is already warm) and returns
    per-thread aggregates as O(1) dict reads.

    Returns ``(0, "")`` for threads that have no indexed docs —
    identical to the previous behavior where ``list_documents`` would
    return an empty list.
    """
    # Build / refresh the reverse index on first use. After that, every
    # mutation (add_chunks / delete_by_doc_id / delete_by_thread_id)
    # keeps it in sync incrementally, so subsequent calls are pure
    # dict reads — no LanceDB scan at all.
    if not _thread_to_docs and not _doc_to_threads:
        _build_reverse_index_from_disk()
    with _reverse_index_lock:
        out: dict[str, tuple[int, str]] = {}
        for tid in tids:
            docs = _thread_to_docs.get(tid, set())
            out[tid] = (len(docs), _thread_first_filename.get(tid, ""))
        return out


def latest_ingested_at_by_threads(tids: Iterable[str]) -> dict[str, str]:
    """For each requested thread_id, return the most recent ``ingested_at``
    ISO 8601 string across all chunks owned by that thread.

    Empty string when the thread has no indexed chunks (matches the
    pre-v2.0.6 wire contract for threads with zero docs — the sidebar
    falls back to whatever else it has for sorting).

    v2.0.6 P2-1 — ``GET /sessions`` doc-only threads used to return
    ``updated_at=""`` because there was no LangGraph checkpoint to read
    from. With this helper the route populates ``updated_at`` from
    ``max(ingested_at)`` instead, so doc-only threads sort correctly
    in the sidebar.

    Like :func:`count_documents_by_threads` this is O(1) dict reads
    once the reverse index is warm — no per-thread LanceDB scan.
    """
    if not _thread_to_docs and not _doc_to_threads:
        _build_reverse_index_from_disk()
    with _reverse_index_lock:
        return {
            tid: _thread_latest_ingested_at.get(tid, "") for tid in tids
        }


