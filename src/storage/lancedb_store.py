# ----------------------------------------------------------------------
# TTL cache for list_documents(thread_id)
# ----------------------------------------------------------------------
# Why this exists
# ----------------
# ``list_documents`` is the per-turn ``route_query`` hook. It runs a
# full LanceDB ``to_arrow()`` scan plus a Python group-by on every chat
# turn that isn't an obvious greeting (so basically every "real"
# question). Measured at 30-200 ms / call on a thread with hundreds of
# chunks. Caching the per-thread result for a few seconds collapses the
# per-turn cost of conversational follow-ups to ~0 ms — the cheap
# routing LLM only needs the same document list the previous turn
# produced.
#
# Why TTL instead of strict invalidation
# --------------------------------------
# Strict invalidation would need to fire on:
#   - every doc-registry status transition (pending→indexed, etc.)
#   - every chunk add (we do invalidate here)
#   - every doc delete (we do invalidate here)
#   - every thread delete (we do invalidate here)
# But status transitions are noisy (the registry flips between
# states many times during a single upload), and they don't actually
# change what the routing LLM needs to know (filenames + a count).
# A 5-second TTL means the worst-case staleness window is bounded
# AND we can be loose about which registry events invalidate. The
# big correctness-critical events (chunks landing, doc deleted) still
# invalidate synchronously.

_THREAD_DOC_CACHE_TTL_SEC = 5.0
_thread_doc_cache: dict[str, tuple[float, list[dict]]] = {}
_thread_doc_cache_lock = threading.Lock()

# v2.0.7 perf-3: separate TTL cache for ``list_chunks_by_thread``,
# which is called on every summary-intent turn by the agent's
# ``summary`` path. With a 50 K-chunk corpus the full scan was costing
# 200-500 ms per summary turn — see the perf survey. TTL is set
# longer than the doc cache (30 s vs 5 s) because summary reads
# dominate the write rate during the relevant window and stale
# chunks do not change the answer materially until the user
# uploads more files.
_THREAD_CHUNK_CACHE_TTL_SEC = 30.0
_thread_chunk_cache: dict[str, tuple[float, list[dict]]] = {}
_thread_chunk_cache_lock = threading.Lock()


def list_documents_cached(thread_id: str | None) -> list[dict]:
    """Cache front for :func:`list_documents` keyed by ``thread_id``
    with a 5-second TTL.

    Use this on the chat / routing hot path where the calling code
    only needs to know "what docs does this thread have" and can
    tolerate a few seconds of staleness. Use :func:`list_documents`
    directly when you need a fresh read (e.g. the docs-list endpoint
    that powers the sidebar — the user expects immediate feedback
    after a delete).

    Returns the cached value if it exists and is younger than the TTL,
    otherwise calls :func:`list_documents` and stores the result.

    Thread-safe: the lookup + insert pair is serialized with a lock so
    two concurrent callers can't both observe an empty cache and both
    run the full scan.
    """
    key = thread_id if thread_id else "__no_thread__"
    now = time.monotonic()
    with _thread_doc_cache_lock:
        cached = _thread_doc_cache.get(key)
        if cached is not None:
            ts, value = cached
            if now - ts < _THREAD_DOC_CACHE_TTL_SEC:
                return value
    value = list_documents(thread_id=thread_id)
    with _thread_doc_cache_lock:
        _thread_doc_cache[key] = (now, value)
    return value


def invalidate_thread_doc_cache(thread_id: str | None = None) -> None:
    """Drop one thread's cached ``list_documents`` result, or all of them.

    Pass ``thread_id`` to drop just that thread (used by ``add_chunks``
    and ``delete_by_thread_id``). Pass ``None`` (the default) to clear
    the entire cache — used by ``delete_by_doc_id`` (we don't know
    which thread the doc belonged to without another scan) and by
    ``reset_for_tests``.
    """
    with _thread_doc_cache_lock:
        if thread_id is None:
            _thread_doc_cache.clear()
            return
        _thread_doc_cache.pop(thread_id if thread_id else "__no_thread__", None)


def list_chunks_by_thread_cached(thread_id: str | None) -> list[dict]:
    """Cache front for :func:`list_chunks_by_thread` keyed by ``thread_id``
    with a 30-second TTL.

    v2.0.7 perf-3 — mirrors :func:`list_documents_cached` for the
    summary-intent hot path. The summary turn flow (see
    ``src/agent/nodes/retrieve.py``) calls ``list_chunks_by_thread``
    on every invocation; on a 50 K-chunk corpus this was a 200-500 ms
    full scan per turn. Caching saves the scan when the corpus
    hasn't changed within the TTL window.

    Use this on the summary / chat hot path. Use
    :func:`list_chunks_by_thread` directly when you need a fresh
    read (e.g. right after a delete where staleness would be
    user-visible).
    """
    key = thread_id if thread_id else "__no_thread__"
    now = time.monotonic()
    with _thread_chunk_cache_lock:
        cached = _thread_chunk_cache.get(key)
        if cached is not None:
            ts, value = cached
            if now - ts < _THREAD_CHUNK_CACHE_TTL_SEC:
                return value
    value = list_chunks_by_thread(thread_id=thread_id)
    with _thread_chunk_cache_lock:
        _thread_chunk_cache[key] = (now, value)
    return value


def invalidate_thread_chunk_cache(thread_id: str | None = None) -> None:
    """Drop one thread's cached ``list_chunks_by_thread`` result.

    Pass ``thread_id`` to drop just that thread; pass ``None`` to
    clear every entry. Same invalidation contract as
    :func:`invalidate_thread_doc_cache`.
    """
    with _thread_chunk_cache_lock:
        if thread_id is None:
            _thread_chunk_cache.clear()
            return
        _thread_chunk_cache.pop(thread_id if thread_id else "__no_thread__", None)
